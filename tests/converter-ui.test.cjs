'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.BROWSER_PATH||chromium.executablePath(),headless:true});
 try {
  const context=await browser.newContext({offline:!/^https?:/.test(process.env.STUDIO_URL||''),acceptDownloads:true});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>d.accept());
  await page.goto(process.env.STUDIO_URL||pathToFileURL(path.join(root,'index.html')).href);
  await page.waitForFunction(()=>document.querySelector('#build-status').textContent.includes('slides'));
  assert.equal(await page.locator('#open-converter').count(),1,'Studio needs a separate draft converter');
  const original=await page.locator('#notes').inputValue();
  await page.locator('#open-converter').click();
  assert.equal(await page.locator('#converter-dialog').isVisible(),true);
  await page.locator('#converter-title').fill('Draft lecture');
  await page.locator('#converter-source').fill('Trade policy\n\nPolicy choices\n- Lower tariffs\n- Public investment');
  await page.locator('#convert-text').click();
  await page.waitForFunction(()=>!document.querySelector('#converter-add').disabled);
  const draft=await page.locator('#converter-draft').inputValue();
  assert.match(draft,/# Draft lecture/);assert.match(draft,/Lower tariffs/);
  assert.equal(await page.locator('#notes').inputValue(),original,'Conversion must not replace existing notes');
  await page.locator('#converter-draft').fill(draft+'\n\n## Cleanup question\n- What would you choose?\n');
  await page.locator('#converter-add').click();
  assert.equal(await page.locator('#lecture-list li').count(),2);
  assert.equal(await page.locator('#available').isChecked(),false,'Drafts start unavailable');
  assert.match(await page.locator('#notes').inputValue(),/Cleanup question/);
  await page.locator('#lecture-list button').first().click();assert.equal(await page.locator('#notes').inputValue(),original);
  await page.locator('#open-converter').click();await page.locator('#converter-source').fill('Cancelled words');
  await page.locator('#converter-close').click();assert.equal(await page.locator('#lecture-list li').count(),2);
  await page.locator('#notes').fill(original+'\n\n## Pending edit\n- Pending edit before conversion\n');
  await page.locator('#open-converter').click();await page.locator('#converter-close').click();
  await page.waitForFunction(()=>document.querySelector('#preview').srcdoc.includes('Pending edit before conversion'),{}, {timeout:3000});
  assert.equal(await page.locator('#open-converter').evaluate(el=>document.activeElement===el),true,'Close restores focus');
  // Real files use the same reviewed-new-lecture path; no input HTML is rendered.
  await page.locator('#open-converter').click();await page.locator('#converter-title').fill('');
  await page.locator('#converter-file').setInputFiles({name:'outline.txt',mimeType:'text/plain',buffer:Buffer.from('Imported outline\n\nChoices\n1. First option\n2. Second option')});
  await page.waitForFunction(()=>document.querySelector('#converter-draft').value.includes('Second option'));
  assert.match(await page.locator('#converter-draft').inputValue(),/^# /);
  await page.locator('#converter-file').setInputFiles({name:'notes.md',mimeType:'text/markdown',buffer:Buffer.from('# Markdown lecture\n\n## Markdown topic\n- Markdown point')});
  await page.waitForFunction(()=>document.querySelector('#converter-draft').value.includes('Markdown point'));
  const unexpected=[];page.on('request',r=>{if(r.url().includes('must-not-load.invalid'))unexpected.push(r.url());});
  const html='<html><body><section class="slide"><h1>Imported HTML lecture</h1></section><section class="slide"><h2>HTML topic</h2><ul><li>Public HTML point</li></ul><aside class="notes">PRIVATE_HTML_TEACHER_NOTE</aside><img src="https://must-not-load.invalid/image.png"></section><script>window.UNSAFE_IMPORTED_SCRIPT=true;</script></body></html>';
  await page.locator('#converter-file').setInputFiles({name:'slides.html',mimeType:'text/html',buffer:Buffer.from(html)});
  await page.waitForFunction(()=>document.querySelector('#converter-draft').value.includes('Public HTML point'));
  assert.equal(await page.evaluate(()=>window.UNSAFE_IMPORTED_SCRIPT),undefined);
  assert.deepEqual(unexpected,[],'Imported HTML must not load external resources');
  await page.locator('#converter-file').setInputFiles(path.join(root,'tests/fixtures/draft-import.pptx'));
  await page.waitForFunction(()=>document.querySelector('#converter-draft').value.includes('Public investment'));
  const pptx=await page.locator('#converter-draft').inputValue();
  for(const word of ['Synthetic import lesson','Opening context','Policy choices','Lower tariffs','Distributional consequences','Comparison table','Option','Outcome','Capacity','PRIVATE_PPTX_TEACHER_NOTE'])assert.ok(pptx.includes(word),'PPTX preserves '+word);
  const publicHTML=await page.evaluate(notes=>window.ChartroomRenderer.renderDeck(window.ChartroomParser.parse(notes)),pptx);
  assert.ok(!publicHTML.includes('PRIVATE_PPTX_TEACHER_NOTE'),'Speaker notes cannot leak to public export');
  assert.ok(publicHTML.includes('Lower tariffs'));
  assert.deepEqual(await page.evaluate(notes=>window.ChartroomParser.parse(notes).diagnostics.filter(d=>d.severity==='error'),pptx),[]);
  let event=page.waitForEvent('download');await page.locator('#converter-save').click();
  assert.equal(fs.readFileSync(await(await event).path(),'utf8'),pptx);
  await page.locator('#converter-file').setInputFiles({name:'broken.txt',mimeType:'text/plain',buffer:Buffer.from([0xC3,0x28])});
  await page.waitForFunction(()=>document.querySelector('#converter-status').textContent.includes('UTF-8'),{}, {timeout:3000});
  assert.equal(await page.locator('#converter-draft').inputValue(),pptx,'Invalid text encoding does not replace the previous draft');
  await page.locator('#converter-file').setInputFiles({name:'old.ppt',mimeType:'application/vnd.ms-powerpoint',buffer:Buffer.from('unsupported')});
  await page.waitForFunction(()=>document.querySelector('#converter-status').textContent.includes('Conversion stopped'));
  assert.equal(await page.locator('#converter-draft').inputValue(),pptx,'An unsupported file does not destroy the previous draft');
  assert.match(await page.locator('#converter-status').textContent(),/pptx/);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#converter-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'Dialog fits narrow screens');
  const artifacts=path.join(root,'tests/artifacts');fs.mkdirSync(artifacts,{recursive:true});
  await page.screenshot({path:path.join(artifacts,'converter-mobile.png')});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:path.join(artifacts,'converter-desktop.png')});
  await page.locator('#converter-add').click();
  assert.equal(await page.locator('#available').isChecked(),false);
  // Let iframe hit-testing catch up after closing the scrolled dialog and moving the page.
  await page.locator('#available').scrollIntoViewIfNeeded();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.locator('#available').check();
  await page.locator('#rebuild').click();
  event=page.waitForEvent('download');await page.locator('#export-teaching').focus();await page.locator('#export-teaching').press('Enter');
  const exported=fs.readFileSync(await(await event).path());
  assert.ok(exported.includes(Buffer.from('Lower tariffs')));
  assert.ok(!exported.includes(Buffer.from('PRIVATE_PPTX_TEACHER_NOTE')));
  assert.deepEqual(errors,[]);
  console.log('PASS: offline text/txt/md/HTML/real PPTX import, editable draft, save/export, new unavailable lecture, original preservation, private speaker notes, inert HTML/no resource loads, unsupported format recovery, responsive dialog and focus.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
