'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(__dirname,'..');
process.env.TEMP = process.env.TMP = path.join(root,'tests/tmp');
fs.mkdirSync(process.env.TEMP,{recursive:true});
fs.mkdirSync(path.join(root,'tests/artifacts'),{recursive:true});
(async () => {
  const browser = await chromium.launch({executablePath:process.env.BROWSER_PATH || chromium.executablePath(),headless:true});
  try {
    const context = await browser.newContext({offline:true, viewport:{width:1600,height:1100}});
    const page = await context.newPage();
    const errors = [], network = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => {if (/^https?:/.test(r.url())) network.push(r.url());});
    page.on('dialog', d => d.accept());
    await page.goto(pathToFileURL(path.join(root,'index.html')).href);
    assert.equal(await page.locator('#insert-element-kind').count(), 1, 'Element dropdown exists');
    assert.ok(await page.locator('#insert-element-kind optgroup').count() > 1, 'Choices are grouped');
    const notes = page.locator('#notes');
    const source = '# Lecture\n\n## First\n- Exact words.\n\n## Second\n- Untouched.\n';
    await notes.fill(source);
    await notes.evaluate(t => {const at=t.value.indexOf('Exact')+2;t.focus();t.setSelectionRange(at,at);});
    await page.locator('#insert-element-kind').selectOption('footer');
    assert.match(await page.locator('#element-help').innerText(), /bottom/i);
    assert.equal(await page.locator('#element-syntax').innerText(), '@footer Your closing question?');
    await page.locator('#insert-element').click();
    const expected = source.replace('- Exact words.\n','- Exact words.\n@footer Your closing question?\n');
    assert.equal(await notes.inputValue(),expected);
    assert.equal(await notes.evaluate(t=>t.value.slice(t.selectionStart,t.selectionEnd)),'Your closing question?');
    assert.equal(await notes.evaluate(t=>t===document.activeElement),true);
    await notes.press('Control+z');
    assert.equal(await notes.inputValue(),source,'Native undo restores the pre-insertion notes');
    await notes.evaluate(t=>{const at=t.value.indexOf('Exact');t.focus();t.setSelectionRange(at,at+5);});
    await page.locator('#insert-element-kind').selectOption('bold');
    await page.locator('#insert-element').click();
    assert.equal(await notes.inputValue(),source.replace('Exact','**Exact**'));
    await notes.fill('# Lecture\n## Topic\n- Point.\n');
    await page.locator('#insert-element-kind').selectOption('notes');
    await page.locator('#insert-element').click();
    await notes.pressSequentially('PRIVATE_INSERT_TEST');
    await page.locator('#rebuild').click();
    await page.waitForFunction(()=>document.querySelector('#build-status').textContent.includes('0 export errors'));
    await page.getByText('Slide map & private asides', {exact:true}).click();
    assert.match(await page.locator('#slide-map').innerText(),/PRIVATE_INSERT_TEST/);
    assert.ok(!(await page.locator('#preview').getAttribute('srcdoc')).includes('PRIVATE_INSERT_TEST'));
    assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('chartroom-studio-project-v1')).lectures[0].notes.includes('PRIVATE_INSERT_TEST')));
    await notes.evaluate(t=>t.setSelectionRange(t.value.length,t.value.length));
    await page.locator('#insert-element-kind').selectOption('footer');
    await page.locator('#insert-element').click();
    const once = await notes.inputValue();
    await notes.evaluate(t=>t.setSelectionRange(t.value.length,t.value.length));
    await page.locator('#insert-element').click();
    assert.equal(await notes.inputValue(),once,'Duplicate insertion preserves notes');
    assert.match(await page.locator('#element-status').innerText(),/once|already/i);
    for (const kind of ['lens','duo','scholar']) {
      await notes.fill('# Lecture\n');
      await page.locator('#insert-kind').selectOption(kind);
      await page.locator('#insert-slide').click();
      const model = await notes.evaluate(t=>window.ChartroomParser.parse(t.value));
      assert.equal(model.slides[1].kind,kind);
      assert.deepEqual(model.diagnostics.filter(d=>d.severity==='error'),[]);
    }
    await notes.fill('# Lecture\n## A decision\n- Your exact words.\n');
    await page.locator('#insert-element-kind').selectOption('sliders');
    await page.locator('#insert-element').click();
    await page.locator('#rebuild').click();
    await page.locator('#preview-next').click();
    await page.locator('#insert-element-kind').selectOption('takeaway');
    await page.screenshot({path:path.join(root,'tests/artifacts/insert-elements-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No mobile horizontal overflow');
    await page.screenshot({path:path.join(root,'tests/artifacts/insert-elements-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[],'No JS errors');
    assert.deepEqual(network,[],'No network requests');
    console.log('PASS: offline grouped element menu, help and syntax, cursor/selection, native undo, bold, private-note export exclusion, autosave, duplicate protection, added layout templates and mobile fit.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
