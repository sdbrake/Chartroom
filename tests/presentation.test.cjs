'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),{pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const root=path.resolve(__dirname,'..');process.env.TMP=process.env.TEMP=path.join(__dirname,'tmp');
(async()=>{
 const b=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH||chromium.executablePath()});
 try{
  const c=await b.newContext({offline:true,viewport:{width:1440,height:1000}}),p=await c.newPage(),errors=[],requests=[];
  p.on('pageerror',e=>errors.push(e.message));p.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});p.on('dialog',d=>d.accept());
  await p.goto(pathToFileURL(path.join(root,'index.html')).href);
  assert.equal(await p.getByRole('button',{name:'Present lecture',exact:true}).count(),1,'Studio has a Present lecture button');
  await p.locator('#load-demo').click();await p.locator('#palette').selectOption('night-seminar');
  const notes=await p.locator('#notes').inputValue()+'\n*PRESENT_PRIVATE_SENTINEL*\n';
  await p.locator('#notes').fill(notes);await p.locator('#rebuild').click();
  await p.locator('#present-lecture').focus();await p.locator('#present-lecture').press('Enter');
  await p.waitForFunction(()=>document.querySelector('#presentation').dataset.ready==='true');
  const f=await (await p.locator('#presentation iframe').elementHandle()).contentFrame();
  assert.ok(f,'isolated public presentation frame');await f.waitForLoadState();
  assert.equal(await f.locator('body').getAttribute('data-mode'),'teaching');
  assert.equal(await f.locator('body').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(23, 33, 43)');
  assert.ok(!(await f.content()).includes('PRESENT_PRIVATE_SENTINEL'));
  assert.equal(await p.locator('.workspace').evaluate(el=>el.inert),true,'editor is inert');
  assert.equal(await p.evaluate(()=>document.fullscreenElement?.id),'presentation','native fullscreen entered');
  await p.waitForFunction(()=>document.activeElement===document.querySelector('#presentation iframe'));
  await p.waitForFunction(()=>getComputedStyle(document.querySelector('#presentation-toolbar')).opacity==='0',{},{timeout:6000});
  await p.keyboard.press('Tab');
  await p.waitForFunction(()=>document.activeElement.id==='presentation-exit');
  assert.equal(await p.locator('#presentation-toolbar').evaluate(el=>getComputedStyle(el).opacity),'1','Tab exposes the exit control');
  await p.keyboard.press('Shift+Tab');
  await p.waitForFunction(()=>document.activeElement===document.querySelector('#presentation iframe'));
  await p.keyboard.press('Shift+Tab');
  await p.waitForFunction(()=>document.activeElement.id==='presentation-exit',{},{timeout:4000});
  await f.locator('body').click();await p.keyboard.press('ArrowRight');
  await f.waitForFunction(()=>ChartroomPlayer.getState().index===1&&ChartroomPlayer.getState().step===0);
  await p.keyboard.press('Space');await f.waitForFunction(()=>ChartroomPlayer.getState().step===1);
  await p.keyboard.press('End');await f.waitForFunction(()=>ChartroomPlayer.getState().index===ChartroomPlayer.getState().count-1);
  await p.keyboard.press('Home');await f.waitForFunction(()=>ChartroomPlayer.getState().index===0);
  await f.evaluate(async()=>{await Promise.all([...document.images].map(i=>i.decode()));});
  assert.deepEqual(await f.evaluate(()=>ChartroomPlayer.audit().filter(s=>s.overflow)),[]);
  await p.screenshot({path:path.join(__dirname,'artifacts/presentation-desktop.png')});
  await p.keyboard.press('Escape');await p.waitForFunction(()=>document.querySelector('#presentation').hidden);
  assert.equal(await p.locator('#notes').inputValue(),notes);
  assert.equal(await p.locator('#palette').inputValue(),'night-seminar');
  assert.equal(await p.locator('.workspace').evaluate(el=>el.inert),false);
  await p.waitForFunction(()=>document.activeElement.id==='present-lecture');
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
  console.log('PASS: selected lecture presents offline in teaching mode, chosen palette, progressive keyboard navigation, decoded images, no overflow/private notes, Escape restores Studio. Browser '+b.version());
 }finally{await b.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
